import { describe, it, expect, beforeEach } from 'vitest';
import { loadApp, seedProgram } from '../helpers/app.js';

describe('Program PDF export — no fixed-position footer', () => {
  let app;
  beforeEach(() => { app = loadApp(); seedProgram(app); });

  it('removes the "Generated by LiftBuilder" branding text', () => {
    const pdf = app.run(`_buildProgramPDFHtml([1], false)`);
    expect(pdf).not.toMatch(/Generated by LiftBuilder/);
  });

  it('has no position:fixed element (the cause of content overlapping the old footer)', () => {
    const pdf = app.run(`_buildProgramPDFHtml([1], false)`);
    expect(pdf).not.toMatch(/position:\s*fixed/);
  });

  it('reserves no artificial bottom page margin now that there is no footer to clear', () => {
    const pdf = app.run(`_buildProgramPDFHtml([1], false)`);
    expect(pdf).toMatch(/@page\s*\{\s*size:\s*letter;\s*margin:\s*0\.5in;\s*\}/);
  });

  it('still renders week content normally, ending cleanly with no stray footer markup', () => {
    const pdf = app.run(`_buildProgramPDFHtml([1], false)`);
    expect(pdf).toContain('MON');
    expect(pdf.trim().endsWith('</html>')).toBe(true);
    expect(pdf.trim().endsWith('</body>\n</html>')).toBe(true);
  });
});
